package com.sentinel.controllers;

import com.sentinel.models.Alert;
import com.sentinel.models.AlertReviewAudit;
import com.sentinel.repositories.AlertRepository;
import com.sentinel.repositories.AlertReviewAuditRepository;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;
import java.util.stream.Collectors;

@RestController
@RequestMapping("/api/v1/alerts")
@CrossOrigin(origins = "*")
public class AlertController {

    private final AlertRepository alertRepository;
    private final AlertReviewAuditRepository auditRepository;

    public AlertController(AlertRepository alertRepository, AlertReviewAuditRepository auditRepository) {
        this.alertRepository = alertRepository;
        this.auditRepository = auditRepository;
    }

    @GetMapping
    public List<Alert> getAlerts(
            @RequestParam(defaultValue = "1") Integer minLevel,
            @RequestParam(required = false) String reviewStatus,
            @RequestParam(required = false) String disposition) {
        List<Alert> alerts = alertRepository.findByThreatLevelGreaterThanEqualOrderByTimestampDesc(minLevel);
        if (reviewStatus != null && !reviewStatus.isBlank()) {
            alerts = alerts.stream()
                    .filter(a -> reviewStatus.equalsIgnoreCase(a.getReviewStatus()))
                    .collect(Collectors.toList());
        }
        if (disposition != null && !disposition.isBlank()) {
            alerts = alerts.stream()
                    .filter(a -> disposition.equalsIgnoreCase(a.getDisposition()))
                    .collect(Collectors.toList());
        }
        return alerts;
    }

    @PostMapping
    public Alert createAlert(@RequestBody Alert alert) {
        if (alert.getTimestamp() == null) {
            alert.setTimestamp(LocalDateTime.now());
        }
        if (alert.getReviewStatus() == null || alert.getReviewStatus().isBlank()) {
            alert.setReviewStatus("NEW");
        }
        if (alert.getDisposition() == null || alert.getDisposition().isBlank()) {
            alert.setDisposition("NONE");
        }
        if (alert.getEngineVersion() == null || alert.getEngineVersion().isBlank()) {
            alert.setEngineVersion("ai-engine-1.2.0-m5");
        }
        Alert saved = alertRepository.save(alert);

        // Record initial creation audit entry
        AlertReviewAudit audit = new AlertReviewAudit(
                saved.getId(),
                "EMIT_ALERT",
                null,
                saved.getReviewStatus(),
                null,
                saved.getDisposition(),
                "ai-engine-1.2.0-m5",
                "Alert generated by visual intelligence pipeline"
        );
        auditRepository.save(audit);

        return saved;
    }

    @PostMapping("/{id}/acknowledge")
    public ResponseEntity<Alert> acknowledgeAlert(@PathVariable UUID id, @RequestParam UUID userId) {
        return alertRepository.findById(id).map(alert -> {
            String prevStatus = alert.getReviewStatus();
            String prevDisp = alert.getDisposition();

            alert.setAcknowledgedBy(userId);
            alert.setAcknowledgedAt(LocalDateTime.now());
            if ("NEW".equalsIgnoreCase(prevStatus) || prevStatus == null) {
                alert.setReviewStatus("UNDER_REVIEW");
            }
            Alert saved = alertRepository.save(alert);

            AlertReviewAudit audit = new AlertReviewAudit(
                    saved.getId(),
                    "ACKNOWLEDGE",
                    prevStatus,
                    saved.getReviewStatus(),
                    prevDisp,
                    saved.getDisposition(),
                    userId.toString(),
                    "Alert acknowledged by operator"
            );
            auditRepository.save(audit);

            return ResponseEntity.ok(saved);
        }).orElse(ResponseEntity.notFound().build());
    }

    public static class ReviewRequest {
        private String action; // ACKNOWLEDGE, RECORD_DISPOSITION, FLAG_FOLLOWUP, REOPEN, ADD_NOTE
        private String disposition; // RELEVANT, NOT_RELEVANT, UNCERTAIN
        private String reviewStatus; // NEW, UNDER_REVIEW, REVIEWED, NEEDS_FOLLOWUP
        private String reviewerId; // e.g. "DELTA-9"
        private String note;

        public String getAction() { return action; }
        public void setAction(String action) { this.action = action; }

        public String getDisposition() { return disposition; }
        public void setDisposition(String disposition) { this.disposition = disposition; }

        public String getReviewStatus() { return reviewStatus; }
        public void setReviewStatus(String reviewStatus) { this.reviewStatus = reviewStatus; }

        public String getReviewerId() { return reviewerId; }
        public void setReviewerId(String reviewerId) { this.reviewerId = reviewerId; }

        public String getNote() { return note; }
        public void setNote(String note) { this.note = note; }
    }

    @PostMapping("/{id}/review")
    public ResponseEntity<Alert> reviewAlert(@PathVariable UUID id, @RequestBody ReviewRequest request) {
        return alertRepository.findById(id).map(alert -> {
            String prevStatus = alert.getReviewStatus() != null ? alert.getReviewStatus() : "NEW";
            String prevDisp = alert.getDisposition() != null ? alert.getDisposition() : "NONE";

            String action = request.getAction() != null ? request.getAction().toUpperCase() : "RECORD_DISPOSITION";
            String newStatus = prevStatus;
            String newDisp = prevDisp;
            String reviewer = request.getReviewerId() != null && !request.getReviewerId().isBlank()
                    ? request.getReviewerId() : "DELTA-9";

            switch (action) {
                case "ACKNOWLEDGE":
                    newStatus = "UNDER_REVIEW";
                    break;
                case "RECORD_DISPOSITION":
                    newStatus = "REVIEWED";
                    if (request.getDisposition() != null && !request.getDisposition().isBlank()) {
                        newDisp = request.getDisposition().toUpperCase();
                    }
                    break;
                case "FLAG_FOLLOWUP":
                    newStatus = "NEEDS_FOLLOWUP";
                    if (request.getDisposition() != null && !request.getDisposition().isBlank()) {
                        newDisp = request.getDisposition().toUpperCase();
                    }
                    break;
                case "REOPEN":
                    newStatus = "UNDER_REVIEW";
                    newDisp = "NONE";
                    break;
                case "ADD_NOTE":
                    // Keeps existing status and disposition
                    break;
                default:
                    if (request.getReviewStatus() != null) {
                        newStatus = request.getReviewStatus().toUpperCase();
                    }
                    if (request.getDisposition() != null) {
                        newDisp = request.getDisposition().toUpperCase();
                    }
                    break;
            }

            if (request.getReviewStatus() != null && !request.getReviewStatus().isBlank()) {
                newStatus = request.getReviewStatus().toUpperCase();
            }
            if (request.getDisposition() != null && !request.getDisposition().isBlank()) {
                newDisp = request.getDisposition().toUpperCase();
            }

            alert.setReviewStatus(newStatus);
            alert.setDisposition(newDisp);
            alert.setReviewedBy(reviewer);
            alert.setReviewedAt(LocalDateTime.now());
            if (request.getNote() != null && !request.getNote().isBlank()) {
                alert.setReviewerNotes(request.getNote());
            }

            Alert saved = alertRepository.save(alert);

            AlertReviewAudit audit = new AlertReviewAudit(
                    saved.getId(),
                    action,
                    prevStatus,
                    newStatus,
                    prevDisp,
                    newDisp,
                    reviewer,
                    request.getNote()
            );
            auditRepository.save(audit);

            return ResponseEntity.ok(saved);
        }).orElse(ResponseEntity.notFound().build());
    }

    @GetMapping("/{id}/reviews")
    public ResponseEntity<List<AlertReviewAudit>> getReviewHistory(@PathVariable UUID id) {
        if (!alertRepository.existsById(id)) {
            return ResponseEntity.notFound().build();
        }
        return ResponseEntity.ok(auditRepository.findByAlertIdOrderByTimestampAsc(id));
    }
}
